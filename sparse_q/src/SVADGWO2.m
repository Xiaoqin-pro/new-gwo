function [Best,T,info]=SVADGWO2(f,state,~,N,seed)
%SVAD-GWO  Sparse-evaluation Grey Wolf Optimizer with a Verified Archive and
%          Differential Search.
%          融合已验证精英档案与差分搜索的稀疏评价灰狼优化算法.
%
%   Final structure (v2): three candidate sources share one budget of real
%   function evaluations, and no other mechanism is used.
%
%     (1) Leader-guided wolves (N = 50)
%         Standard three-leader GWO aggregation of alpha/beta/delta.
%
%     (2) Differential slots (nG2 = 12)  -- DiffA
%         y = x_r1 + F(t)*(alpha - x_r1) + F(t)*(x_r2 - x_r3)
%         with r1,r2,r3 distinct members of the joint pool of wolves and verified
%         archive solutions, and a contracting scale
%             F(t) = F0 - (F0-F1)*max(0,(t-tc)/(1-tc)),   t = FE/FE_max
%
%     (3) Verified-archive slots (nE = 38)  -- E
%         Credit-weighted single-centre shells and two-centre line segments around
%         verified elites, with a radius adapted to recent verified successful
%         step lengths.
%
%   Only K = 10 of the M = 100 candidates receive a real evaluation each
%   generation.  A candidate is never ranked, promoted to a leader or admitted to
%   the archive without a real evaluation, and every real call is charged once.
%
%   Usage: [Best,T,info] = SVADGWO2(f,state,[],N,seed)
%
%   This file is the proposed algorithm and contains no experimental switches;
%   ablations are generated by ablation/SVADGWO2_ablate.m.

% Frozen configuration (2026-10-25):
%   adaptive evaluation frequency ON  (Kmin=4, Kmax=20, stallTol=2000)
%   adaptive slot allocation OFF      (fixed M=100 = 50/12/38, the ratio the
%                                      ablation needs in order to attribute
%                                      budget to each mechanism)
%   unbiased uniform screening        (see docs/151 for the eleven-rule study)
% Frozen configuration (2026-10-25, v3 "no-pool" structure):
%   M = K = 10        generate exactly what is evaluated; no candidate pool and
%                     therefore no screening rule at all
%   quota 4 / 3 / 3   G1 / DiffA / E share of the 10 real evaluations
%   no STEER, no alpha shells, no adaptive slot or frequency schedules
opts = struct('M',10, 'K',10, 'nG2',3, 'nE',3, ...
              'useE',1, 'useDiff',1, 'adaptSlots',0, 'adaptK',0);
[Best,T,info]=SVADGWO2_core(f,state,N,seed,'diff',0,opts);
end
