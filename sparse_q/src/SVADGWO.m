function [Best,T,info]=SVADGWO(f,state,~,N,seed)
%SVAD-GWO  Sparse-evaluation Grey Wolf Optimizer with a Verified Archive and
%          Differential Search.
%          融合已验证精英档案与差分搜索的稀疏评价灰狼优化算法.
%
%   Sparse-evaluation grey wolf optimizer for expensive black-box problems.
%   Three candidate sources share one budget of real function evaluations:
%
%     (1) Leader-guided wolves (N)
%         Standard GWO aggregation of alpha/beta/delta, optionally extended by an
%         equal-length random-direction perturbation (directional coverage).
%
%     (2) Differential slots (nG2)  -- the DiffA mechanism
%         y = x_r1 + F(t)*(alpha - x_r1) + F(t)*(x_r2 - x_r3)
%         with r1,r2,r3 distinct members of the joint pool of wolves and verified
%         archive solutions, and a contracting scale
%             F(t) = F0 - (F0-F1)*max(0,(t-tc)/(1-tc)),   t = FE/FE_max
%         so the slots behave as differential exploration early and as
%         alpha-centred refinement late.
%
%     (3) Verified-archive slots (nE)  -- the VMA mechanism
%         Credit-weighted single-centre shells and two-centre line segments
%         around verified elites, with a radius adapted to recent verified
%         successful step lengths.
%
%   Only K of the M candidates receive a real evaluation each generation.  A
%   candidate is never ranked, promoted to a leader, or admitted to the archive
%   without a real evaluation, and every real call is charged exactly once.
%
%   Usage: [Best,T,info] = SVADGWO(f,state,[],N,seed)
%
%   This file is the proposed algorithm and contains no experimental switches;
%   ablations are generated by ablation/SVADGWO_ablate.m.

[Best,T,info]=SVADGWO_core(f,state,N,seed,'diff',0,0.5);
end
